"""Build the reproducible analysis package for a run. Spec ``0099`` (REQ-012).

The package's ``dataset_analysis/`` is a byte-for-byte copy of this runtime's
``analysis/`` directory — the code that actually executed — and the manifest
records each module's SHA-256 so anyone can check that.
"""

from __future__ import annotations

import hashlib
import shutil
from pathlib import Path
from typing import Dict

import yaml

from .analysis import pipeline
from .analysis.metadata import library_versions
from .analysis.models import InvestigationState
from .analysis.report import key_findings
from .analysis.utils import pretty_json

ANALYSIS_DIR = Path(__file__).resolve().parent / "analysis"
PACKAGE_VERSION = "1.0.0"


def module_files() -> list:
    return sorted(p for p in ANALYSIS_DIR.glob("*.py"))


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def runtime_module_hashes() -> Dict[str, str]:
    return {f"dataset_analysis/{p.name}": sha256_file(p) for p in module_files()}


def _pyproject(state: InvestigationState, versions: Dict[str, str]) -> str:
    deps = [f'  "{lib}>={v}",' for lib, v in versions.items()]
    return "\n".join([
        "[build-system]", 'requires = ["setuptools>=69"]', 'build-backend = "setuptools.build_meta"', "",
        "[project]", 'name = "dataset-analysis"', f'version = "{PACKAGE_VERSION}"',
        f'description = "Reproducible analysis package for investigation {state.run_id} (QuantSmith spec 0099)."',
        'requires-python = ">=3.10"', "dependencies = [", *deps, "]", "",
        "[project.scripts]", 'dataset-investigator = "dataset_analysis.cli:main"', "",
        "[tool.setuptools]", 'packages = ["dataset_analysis"]', "",
    ])


def _readme(state: InvestigationState) -> str:
    d = state.dataset
    lines = [
        f"# Analysis package — {state.run_id}", "",
        "Generated by the QuantSmith Dataset Investigator (spec `0099`). `dataset_analysis/` is a byte-for-byte",
        "copy of the modules that ran; `manifest.json` lists their SHA-256 hashes and maps every finding to the",
        "function, parameters, and evidence that produced it.", "",
        (f"Dataset: {d.rows:,} rows × {d.columns} columns · file SHA-256 `{d.file_sha256 or 'n/a (in-memory frame)'}` · "
         f"content hash `{d.content_sha256}`"), "",
        "## Install", "", "```sh", "pip install -r requirements.lock", "pip install --no-deps -e .", "```", "",
        "## Use", "", "```sh",
        "dataset-investigator reproduce F001 --data path/to/data.csv   # one finding",
        "dataset-investigator rerun --data path/to/data.csv            # the whole investigation, compared byte for byte",
        "dataset-investigator analyze path/to/other.csv --out run2     # a fresh investigation",
        "DATASET_ANALYSIS_DATA=path/to/data.csv python -m pytest tests -q", "```", "",
        "```python", "from dataset_analysis import investigate", 'state = investigate("path/to/data.csv", out_dir="run")',
        "from dataset_analysis.anomalies import detect_outliers", "```", "",
        "Exit codes: 0 reproduced, 2 usage error, 3 evidence mismatch, 4 wrong dataset.", "",
        "## Findings", "", "| ID | Status | Claim | Function |", "| --- | --- | --- | --- |",
    ]
    for f in state.findings:
        if f.merged_into is None:
            lines.append(f"| {f.finding_id} | {f.status} | {f.claim.replace('|', '/')} | `{f.module}.{f.function}` |")
    return "\n".join(lines) + "\n"


