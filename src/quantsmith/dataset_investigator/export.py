def build_package(state: InvestigationState, run_dir: Path) -> Path:
    """Write ``run_dir/analysis_package/`` around a copy of the executed modules (REQ-012)."""
    run_dir = Path(run_dir)
    report_dir = run_dir / "report"
    if not (report_dir / "findings.json").is_file():
        raise FileNotFoundError("write the report before exporting (findings.json is the expected output)")
    pkg = run_dir / "analysis_package"
    if pkg.exists():
        shutil.rmtree(pkg)
    code = pkg / "dataset_analysis"
    code.mkdir(parents=True)
    for p in module_files():
        shutil.copyfile(p, code / p.name)
    hashes = {f"dataset_analysis/{p.name}": sha256_file(p) for p in sorted(code.glob("*.py"))}
    if hashes != runtime_module_hashes():
        raise RuntimeError("copied modules differ from the runtime's")
    (pkg / "manifest.json").write_text(pretty_json(pipeline.manifest(state, hashes)), encoding="utf-8")
    (pkg / "configs").mkdir()
    (pkg / "configs" / "investigation.yaml").write_text(
        yaml.safe_dump(state.config.model_dump(mode="json"), sort_keys=True), encoding="utf-8")
    (pkg / "expected").mkdir()
    for name in ("findings.json", "hypotheses.json"):
        shutil.copyfile(report_dir / name, pkg / "expected" / name)
    versions = {k: v for k, v in library_versions().items() if k != "quantsmith" and v != "not installed"}
    (pkg / "requirements.lock").write_text("".join(f"{k}=={v}\n" for k, v in sorted(versions.items())), encoding="utf-8")
    (pkg / "pyproject.toml").write_text(_pyproject(state, versions), encoding="utf-8")
    (pkg / "README.md").write_text(_readme(state), encoding="utf-8")
    (pkg / "tests").mkdir()
    (pkg / "tests" / "test_quality.py").write_text(TEST_QUALITY, encoding="utf-8")
    (pkg / "tests" / "test_relationships.py").write_text(TEST_RELATIONSHIPS, encoding="utf-8")
    (pkg / "tests" / "test_pipeline.py").write_text(TEST_PIPELINE, encoding="utf-8")
    (pkg / "examples").mkdir()
    (pkg / "examples" / "reproduce_analysis.py").write_text(EXAMPLE, encoding="utf-8")
    return pkg


def key_finding_ids(state: InvestigationState) -> list:
    return [f.finding_id for f in key_findings(state)]
